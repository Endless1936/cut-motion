export const clippedContentRect = (element, root, readStyle = globalThis.getComputedStyle) => {
  const bounds = element.getBoundingClientRect();
  let { left, top, right, bottom } = bounds;
  // The canvas itself is deliberately excluded: genuine canvas overflow must still fail.
  for (let parent = element.parentElement; parent && parent !== root; parent = parent.parentElement) {
    const style = readStyle(parent);
    if (["inline", "contents"].includes(style.display)) continue;
    // An expanded clip edge can paint outside the ancestor's border rectangle.
    // Keep raw bounds when that edge cannot be represented by this rectangle.
    if ([style.overflowX, style.overflowY].includes("clip")
      && style.overflowClipMargin && style.overflowClipMargin !== "0px") continue;
    // Overflow does not clip positioned descendants whose containing block is
    // outside this ancestor. Unknown/fixed positioning stays conservative.
    let escapes = false;
    for (let child = element; child && child !== parent; child = child.parentElement) {
      const position = readStyle(child).position;
      if (position === "fixed" || (position === "absolute"
        && (!child.offsetParent || (child.offsetParent !== parent && !parent.contains(child.offsetParent))))) {
        escapes = true;
        break;
      }
    }
    if (escapes) continue;
    // Axis-specific clipping cannot be mapped using an AABB after rotation/skew.
    let axisAligned = true;
    for (let ancestor = parent; ancestor; ancestor = ancestor.parentElement) {
      const computed = readStyle(ancestor);
      const transform = computed.transform;
      if (computed.perspective && computed.perspective !== "none") axisAligned = false;
      if (computed.rotate && computed.rotate !== "none" && computed.rotate !== "0deg") axisAligned = false;
      if (transform && transform !== "none") {
        const matrix = /^matrix\(([^)]+)\)$/.exec(transform)?.[1].split(",").map(Number);
        const matrix3d = /^matrix3d\(([^)]+)\)$/.exec(transform)?.[1].split(",").map(Number);
        const planar = matrix?.length === 6 && matrix.every(Number.isFinite)
          && matrix[1] === 0 && matrix[2] === 0 && matrix[0] > 0 && matrix[3] > 0;
        const spatial = matrix3d?.length === 16 && matrix3d.every(Number.isFinite)
          && [1, 2, 3, 4, 6, 7, 8, 9, 11].every((index) => matrix3d[index] === 0)
          && matrix3d[0] > 0 && matrix3d[5] > 0 && matrix3d[10] > 0 && matrix3d[15] === 1;
        if (!planar && !spatial) axisAligned = false;
      }
    }
    if (!axisAligned) continue;
    const clip = parent.getBoundingClientRect();
    if (["hidden", "clip", "scroll", "auto"].includes(style.overflowX)) { left = Math.max(left, clip.left); right = Math.min(right, clip.right); }
    if (["hidden", "clip", "scroll", "auto"].includes(style.overflowY)) { top = Math.max(top, clip.top); bottom = Math.min(bottom, clip.bottom); }
  }
  return { left, top, right, bottom, width: Math.max(0, right - left), height: Math.max(0, bottom - top) };
};
export const findContentCollision = (elements, readRect = (element) => element.getBoundingClientRect()) => {
  for (let leftIndex = 0; leftIndex < elements.length; leftIndex += 1) {
    for (let rightIndex = leftIndex + 1; rightIndex < elements.length; rightIndex += 1) {
      const left = elements[leftIndex];
      const right = elements[rightIndex];
      if (!(left.textContent.trim() || right.textContent.trim())
        || left.dataset.overlapPolicy === "intentional"
        || right.dataset.overlapPolicy === "intentional") continue;
      const leftRect = readRect(left);
      const rightRect = readRect(right);
      if (leftRect.left < rightRect.right - 1 && leftRect.right > rightRect.left + 1
        && leftRect.top < rightRect.bottom - 1 && leftRect.bottom > rightRect.top + 1) {
        return { left, right };
      }
    }
  }
  return null;
};
const pathIsInside = (parent, candidate) => {
  const relative = path.relative(parent, candidate);
  return relative !== "" && !relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative);
};
const assertSafeOutputPath = (directory, outputPath) => {
  const fullOutput = path.join(directory, "index.html");
  const chunkRoot = path.join(directory, "chunks");
  const visualSampleOutput = path.join(directory, "visual-sample", "index.html");
  const chunkOutput = path.basename(outputPath) === "index.html"
    && path.dirname(path.dirname(outputPath)) === chunkRoot;
  if (outputPath !== fullOutput && outputPath !== visualSampleOutput && !chunkOutput) {
    throw new Error("Composition output must be hyperframes/index.html, hyperframes/visual-sample/index.html, or hyperframes/chunks/<chunk>/index.html");
  }
  let existingAncestor = path.dirname(outputPath);
  while (!fs.existsSync(existingAncestor)) existingAncestor = path.dirname(existingAncestor);
  const realDirectory = fs.realpathSync(directory);
  const realAncestor = fs.realpathSync(existingAncestor);
  if (realAncestor !== realDirectory && !pathIsInside(realDirectory, realAncestor)) {
    throw new Error("Composition output resolves outside the HyperFrames directory");
  }
  if (fs.existsSync(outputPath)) {
    const stat = fs.lstatSync(outputPath);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error("Composition output must be a regular file");
  }
};
const moduleDirectories = (directory) => {
  const mgDirectory = path.join(directory, "mg");
  if (!fs.existsSync(mgDirectory)) return [];
  return fs.readdirSync(mgDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
};

const assertModuleSource = (beatId, fragment, timeline) => {
  const rootMatches = [...fragment.matchAll(/data-beat-id=["']([^"']+)["']/g)];
  if (rootMatches.length !== 1 || rootMatches[0][1] !== beatId) {
    throw new Error(`${beatId}: fragment.html must contain exactly one data-beat-id="${beatId}" root`);
  }
  if (new RegExp(`\\bid\\s*=\\s*["']mg-${beatId}["']`, "i").test(fragment)) {
    throw new Error(`${beatId}: fragment.html cannot use reserved generated wrapper ID "mg-${beatId}"`);
  }
  if (/<(?:script|style|video|audio)\b/i.test(fragment)) {
    throw new Error(`${beatId}: fragment.html contains a forbidden shared element`);
  }
  if (/^\s*(?:import|export)\b/m.test(timeline) || /\bgsap\s*\.\s*timeline\s*\(/.test(timeline)) {
    throw new Error(`${beatId}: timeline.mjs must append to the supplied timeline without imports or a second timeline`);
  }
};

export const bindFaceCoverApproval = (fragment, beat) => {
  const approved = beat.layout?.faceCoverApproval === "user"
    && typeof beat.layout?.faceSafetyNote === "string" && beat.layout.faceSafetyNote.trim();
  if ((beat.layout?.faceCoverApproval !== undefined || /\bdata-face-cover-approval\s*=/i.test(fragment)) && !approved) {
    throw new Error(`${beat.id}: face coverage requires a recorded user instruction in the Beat Map`);
  }
  return fragment.replace(/<[a-z][^>]*>/gi, (tag) => {
    const clean = tag.replace(/\sdata-face-cover-approval\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, "");
    const axis = /\sdata-axis\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i.exec(clean);
    return approved && /\sdata-motion-group(?:\s|=|>)/i.test(clean) && (axis?.[1] ?? axis?.[2] ?? axis?.[3]) === "A"
      ? clean.replace(/>$/, ' data-face-cover-approval="user">') : clean;
  });
};

const transformCaptionLayers = (source, startFrame, endFrame, fps) => {
  const windows = [...source.matchAll(/<section\b(?=[^>]*\bmotion-caption-layer\b)[^>]*>/gi)].map(([tag]) => ({
    id: /\bdata-caption-id=["']([^"']+)["']/.exec(tag)?.[1],
    startFrame: Number(/\bdata-caption-start-frame=["'](\d+)["']/.exec(tag)?.[1]),
    endFrame: Number(/\bdata-caption-end-frame=["'](\d+)["']/.exec(tag)?.[1])
  }));
  assertCaptionSequence(windows);
  return source.replace(
  /<section\b(?=[^>]*\bmotion-caption-layer\b)[^>]*>[\s\S]*?<\/section>/gi,
  (section) => {
    const tag = /^<section\b[^>]*>/i.exec(section)?.[0];
    if (!tag) return section;
    const cueStart = Number(/\bdata-caption-start-frame=["'](\d+)["']/.exec(tag)?.[1]);
    const cueEnd = Number(/\bdata-caption-end-frame=["'](\d+)["']/.exec(tag)?.[1]);
    const overlap = intersectFrameWindows(
      captionFrameWindow({ id: /\bdata-caption-id=["']([^"']+)["']/.exec(tag)?.[1], startFrame: cueStart, endFrame: cueEnd }),
      { startFrame, endFrame }
    );
    if (!overlap) return "";
    const { start: localStart, duration } = frameWindowTiming({
      startFrame: overlap.startFrame - startFrame,
      endFrame: overlap.endFrame - startFrame
    }, fps);
    const transformedTag = tag
      .replace(/\bdata-start=["'][^"']+["']/, `data-start="${localStart}"`)
      .replace(/\bdata-duration=["'][^"']+["']/, `data-duration="${duration}"`);
    return section.replace(tag, transformedTag);
  }
  );
};

const mediaAttribute = (tag, name) => new RegExp(`\\b${name}=["']([^"']*)["']`, "i").exec(tag)?.[1] ?? "";
const replaceMediaAttribute = (tag, name, value) => {
  const pattern = new RegExp(`\\b${name}\\s*=\\s*(["'])[^"']*\\1`, "i");
  if (pattern.test(tag)) return tag.replace(pattern, `${name}="${value}"`);
  return tag.replace(/\/?\s*>$/, ` ${name}="${value}"$&`);
};

// Direct media keeps its authored global window, while a chunk receives a
// local media window and the corresponding source offset. The main GSAP
// timeline is global; only media attributes need this physical clipping.
const transformTimedRootMedia = (source, startFrame, endFrame, fps, fullDuration) => {
  const windowStart = seconds(startFrame, fps);
  const windowEnd = seconds(endFrame, fps);
  const windowDuration = windowEnd - windowStart;
  return source.replace(/<(video|audio)\b[^>]*>/gi, (tag) => {
    const startValue = mediaAttribute(tag, "data-start");
    const durationValue = mediaAttribute(tag, "data-duration");
    const clipStart = Number(startValue);
    const clipDuration = durationValue === "__CUT_MOTION_DURATION__"
      ? fullDuration
      : Number(durationValue);
    if (!Number.isFinite(clipStart) || !Number.isFinite(clipDuration) || clipDuration <= 0) return tag;
    const clipEnd = clipStart + clipDuration;
    const overlapStart = Math.max(clipStart, windowStart);
    const overlapEnd = Math.min(clipEnd, windowEnd);
    const sourceStart = Number(mediaAttribute(tag, "data-media-start"));
    const mediaStart = Number.isFinite(sourceStart) ? sourceStart : 0;
    if (overlapEnd <= overlapStart) {
      return replaceMediaAttribute(
        replaceMediaAttribute(
          replaceMediaAttribute(tag, "data-start", decimal(windowDuration + 1 / fps)),
          "data-duration",
          decimal(1 / fps)
        ),
        "data-media-start",
        decimal(mediaStart)
      );
    }
    return replaceMediaAttribute(
      replaceMediaAttribute(
        replaceMediaAttribute(tag, "data-start", decimal(overlapStart - windowStart)),
        "data-duration",
        decimal(overlapEnd - overlapStart)
      ),
      "data-media-start",
      decimal(mediaStart + overlapStart - clipStart)
    );
  });
};

// Root media groups use the authored global timeline in the full composition.
// A localized chunk needs the same group lifetime expressed in local seconds,
// otherwise the runtime contract compares local playhead time with global
// group bounds and rejects an otherwise valid preview/render.
const transformTimedRootMotionGroups = (source, startFrame, endFrame, fps, fullDuration) => {
  const totalFrames = Math.ceil(fullDuration * fps);
  if (startFrame === 0 && endFrame === totalFrames) return source;
  const windowStart = seconds(startFrame, fps);
  const windowEnd = seconds(endFrame, fps);
  const windowDuration = windowEnd - windowStart;
  return source.replace(/<[^>]*\bdata-motion-group(?:\s|=|>)[^>]*>/gi, (tag) => {
    const groupStartValue = mediaAttribute(tag, "data-group-start");
    const groupDurationValue = mediaAttribute(tag, "data-group-duration");
    const groupStart = Number(groupStartValue);
    const groupDuration = groupDurationValue === "__CUT_MOTION_DURATION__"
      ? fullDuration
      : Number(groupDurationValue);
    if (!Number.isFinite(groupStart) || !Number.isFinite(groupDuration) || groupDuration <= 0) return tag;
    const groupEnd = groupStart + groupDuration;
    const overlapStart = Math.max(groupStart, windowStart);
    const overlapEnd = Math.min(groupEnd, windowEnd);
    if (overlapEnd <= overlapStart) {
      return replaceMediaAttribute(
        replaceMediaAttribute(tag, "data-group-start", decimal(windowDuration + 1 / fps)),
        "data-group-duration",
        decimal(1 / fps)
      );
    }
    return replaceMediaAttribute(
      replaceMediaAttribute(tag, "data-group-start", decimal(overlapStart - windowStart)),
      "data-group-duration",
      decimal(overlapEnd - overlapStart)
    );
  });
};

const ensureLocalResourceLinks = (compositionDirectory, sourceDirectory) => {
  fs.mkdirSync(compositionDirectory, { recursive: true });
  for (const name of ["assets", "caption.css"]) {
    const source = path.join(sourceDirectory, name);
    if (!fs.existsSync(source)) continue;
    const target = path.join(compositionDirectory, name);
    if (name === "caption.css") {
      if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) fs.unlinkSync(target);
      if (fs.existsSync(target) && !fs.lstatSync(target).isFile()) {
        throw new Error("Localized caption.css must be a regular file");
      }
      fs.copyFileSync(source, target);
      continue;
    }
    if (fs.existsSync(target)) {
      if (fs.realpathSync(target) !== fs.realpathSync(source)) {
        throw new Error(`Localized composition resource conflicts with ${name}`);
      }
      continue;
    }
    fs.symlinkSync(
      path.relative(compositionDirectory, source),
      target,
      fs.statSync(source).isDirectory() && process.platform === "win32" ? "junction" : undefined
    );
  }
};

export const buildComposition = (hyperframesDirectory, options = {}) => {
  const directory = path.resolve(hyperframesDirectory);
  const outputPath = path.resolve(options.outputPath ?? path.join(directory, "index.html"));
  assertSafeOutputPath(directory, outputPath);
  const jobRoot = path.dirname(directory);
  const beatMapPath = path.join(jobRoot, "state", "beat-map.json");
  const transcriptPath = path.join(jobRoot, "state", "transcript.json");
  const beatMap = fs.existsSync(beatMapPath) ? readJson(beatMapPath) : { duration: 10, fps: 30, beats: [] };
  const transcript = fs.existsSync(transcriptPath) ? readJson(transcriptPath) : { segments: [] };
  const fps = Number(beatMap.fps ?? 30);
  const fullDuration = Number(beatMap.duration ?? 10);
  if (!Number.isFinite(fps) || fps <= 0 || !Number.isFinite(fullDuration) || fullDuration <= 0) {
    throw new Error("Beat Map requires positive fps and duration");
  }

  const totalFrames = Math.ceil(fullDuration * fps);
  const frameGridDuration = totalFrames / fps;
  const startFrame = options.startFrame == null ? 0 : Number(options.startFrame);
  const endFrame = options.endFrame == null ? totalFrames : Number(options.endFrame);
  if (!Number.isInteger(startFrame) || !Number.isInteger(endFrame)
    || startFrame < 0 || endFrame <= startFrame || endFrame > totalFrames) {
    throw new Error(`Composition requires a half-open integer frame window within [0, ${totalFrames})`);
  }

  const beats = new Map();
  for (const beat of beatMap.beats ?? []) {
    if (!BEAT_ID_PATTERN.test(beat.id ?? "")) {
      throw new Error(`Invalid Beat ID "${beat.id ?? ""}": use lowercase letters, numbers, and hyphens`);
    }
    if (beats.has(beat.id)) throw new Error(`Duplicate Beat ID "${beat.id}"`);
    beats.set(beat.id, beat);
  }
  const moduleIds = moduleDirectories(directory);
  for (const beat of beats.values()) {
    const requiresModule = beatMap.captionMode === "motion-copy" || beat.mgScope === "local";
    if (requiresModule && !moduleIds.includes(beat.id)) {
      throw new Error(`${beat.id}: approved motion Beat is missing its MG module`);
    }
  }
  const wordsById = transcriptWordsById(transcript);
  const sourcePath = path.join(directory, "index.template.html");
  let source = fs.readFileSync(sourcePath, "utf8");
  for (const marker of [STYLE_MARKER, FRAGMENT_MARKER, TIMELINE_MARKER, COLLISION_MARKER]) {
    if (!source.includes(marker)) throw new Error(`Composition template is missing ${marker}`);
  }

  const windowStart = seconds(startFrame, fps);
  const windowEnd = seconds(endFrame, fps);
  const styles = [];
  const fragments = [];
  const timelines = [];
  const includedBeatIds = [];
  let trackIndex = 10;

  for (const beatId of moduleIds) {
    const beat = beats.get(beatId);
    if (!beat) throw new Error(`${beatId}: MG module has no matching Beat Map entry`);
    const moduleDirectory = path.join(directory, "mg", beatId);
    const sources = Object.fromEntries(["fragment.html", "style.css", "timeline.mjs"].map((filename) => {
      const filePath = path.join(moduleDirectory, filename);
      if (!fs.existsSync(filePath)) throw new Error(`${beatId}: missing ${filename}`);
      return [filename, fs.readFileSync(filePath, "utf8").trim()];
    }));
    assertModuleSource(beatId, sources["fragment.html"], sources["timeline.mjs"]);
    sources["fragment.html"] = bindFaceCoverApproval(sources["fragment.html"], beat);

    const renderWindow = resolveBeatRenderWindow(beat, beatMap, wordsById);
    const renderStartFrame = Math.max(0, Math.floor(renderWindow.start * fps));
    const renderEndFrame = Math.min(totalFrames, Math.ceil(renderWindow.end * fps));
    const clipStartFrame = Math.max(renderStartFrame, startFrame);
    const clipEndFrame = Math.min(renderEndFrame, endFrame);
    if (clipEndFrame <= clipStartFrame) continue;

    // Keep independent group lifetimes when a fragment has more than one
    // group. Only replace missing or stale metadata with the current Beat Map
    // window; transformTimedRootMotionGroups localizes each group later.
    const fragment = sources["fragment.html"].replace(
      /<[^>]*\bdata-motion-group(?:\s|=|>)[^>]*>/gi,
      (tag) => {
        const groupStart = Number(mediaAttribute(tag, "data-group-start"));
        const groupDuration = Number(mediaAttribute(tag, "data-group-duration"));
        const groupEnd = groupStart + groupDuration;
        const tolerance = 1 / fps;
        const isCurrent = Number.isFinite(groupStart)
          && Number.isFinite(groupDuration)
          && groupDuration > 0
          && groupStart >= renderWindow.start - tolerance
          && groupEnd <= renderWindow.end + tolerance;
        if (isCurrent) return tag;
        return replaceMediaAttribute(
          replaceMediaAttribute(tag, "data-group-start", decimal(renderWindow.start)),
          "data-group-duration",
          decimal(renderWindow.end - renderWindow.start)
        );
      }
    );
    const rootSelector = beatRootSelector(beatId);
    includedBeatIds.push(beatId);
    styles.push(`/* ${beatId} */\n@scope (#mg-${beatId}) {\n${sources["style.css"]}\n}`);
    fragments.push([
      `<section id="mg-${beatId}" class="clip" data-mg-beat-id="${beatId}" data-start="${seconds(clipStartFrame - startFrame, fps)}" data-duration="${seconds(clipEndFrame - clipStartFrame, fps)}" data-track-index="${trackIndex}">`,
      fragment,
      "</section>"
    ].join("\n"));
    timelines.push([
      `// ${beatId}`,
      "{",
      `  const beat = Object.freeze({ id: ${JSON.stringify(beatId)}, start: ${decimal(beat.start)}, duration: ${decimal(beat.end - beat.start)}, entryAnchorTime: ${decimal(renderWindow.entryAnchorTime)}, exitAnchorTime: ${decimal(renderWindow.exitAnchorTime)}, exitStartTime: ${decimal(renderWindow.exitStartTime)}, exitDuration: ${renderWindow.exitDuration} });`,
      `  const root = document.querySelector(${JSON.stringify(rootSelector)});`,
      `  if (!root) throw new Error(${JSON.stringify(`${beatId}: Beat root is missing`)});`,
      "  const select = (selector) => [...root.querySelectorAll(selector)].filter((node) => root.contains(node));",
      sources["timeline.mjs"].split("\n").map((line) => `  ${line}`).join("\n"),
      "  timeline.to(root, { autoAlpha: 0, duration: beat.exitDuration, ease: \"power2.in\" }, beat.exitStartTime);",
      "}"
    ].join("\n"));
    trackIndex += 1;
  }

  const duration = seconds(endFrame - startFrame, fps);
  source = transformCaptionLayers(source, startFrame, endFrame, fps)
    .replace(STYLE_MARKER, `${STYLE_MARKER}\n${styles.join("\n\n")}`)
    .replace(FRAGMENT_MARKER, `${FRAGMENT_MARKER}\n${fragments.join("\n")}`)
    .replace(COLLISION_MARKER, `const findContentCollision = ${findContentCollision.toString()};\nconst clippedContentRect = ${clippedContentRect.toString()};`)
    .replace(TIMELINE_MARKER, `${TIMELINE_MARKER}\n${timelines.join("\n\n")}`);
  // Apply chunk-local transforms after MG fragments have been inserted so
  // their motion-group bounds use the same local clock as root media groups.
  source = transformTimedRootMedia(source, startFrame, endFrame, fps, frameGridDuration);
  source = transformTimedRootMotionGroups(source, startFrame, endFrame, fps, frameGridDuration);
  source = source
    .replaceAll("__CUT_MOTION_DURATION__", String(duration))
    .replaceAll("__CUT_MOTION_MEDIA_START__", String(windowStart));
  source = source.replaceAll("data-template-composition-id", "data-composition-id");
  if (options.videoOnly === true) {
    source = source.replace(/\s*<audio\b[^>]*><\/audio>\s*/gi, "\n");
  }

  const outputDirectory = path.dirname(outputPath);
  if (outputDirectory !== directory) ensureLocalResourceLinks(outputDirectory, directory);
  const output = /^\s*<!doctype\b[^>]*>/i.test(source)
    ? source.replace(/^(\s*<!doctype\b[^>]*>)/i, `$1\n${GENERATED_HEADER}`)
    : `${GENERATED_HEADER}\n${source}`;
  fs.mkdirSync(outputDirectory, { recursive: true });
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
    fs.writeFileSync(outputPath, output);
  }
  return {
    outputPath,
    duration,
    windowStart,
    windowEnd,
    startFrame,
    endFrame,
    beatIds: includedBeatIds
  };
};

export const rebuildVisualSample = (hyperframesDirectory) => {
  const directory = path.resolve(hyperframesDirectory);
  const outputPath = path.join(directory, "visual-sample", "index.html");
  if (!fs.existsSync(outputPath)) throw new Error("Visual sample source is missing");
  const outputStat = fs.lstatSync(outputPath);
  if (!outputStat.isFile() || outputStat.isSymbolicLink()
    || !pathIsInside(fs.realpathSync(directory), fs.realpathSync(outputPath))) {
    throw new Error("Visual sample source must be a regular file inside the HyperFrames directory");
  }
  const source = fs.readFileSync(outputPath, "utf8");
  const rootTag = /<[^>]+\bdata-composition-id=["']main["'][^>]*>/i.exec(source)?.[0];
  const videoTag = /<video\b(?=[^>]*\bid=["']a-roll["'])[^>]*>/i.exec(source)?.[0];
  const attribute = (tag, name) => Number(new RegExp(`\\b${name}=["']([^"']+)["']`, "i").exec(tag ?? "")?.[1]);
  const fps = attribute(rootTag, "data-fps");
  const mediaStart = attribute(videoTag, "data-media-start");
  const duration = attribute(rootTag, "data-duration");
  const exactFrame = (value, label) => {
    const frame = value * fps;
    const rounded = Math.round(frame);
    if (!Number.isFinite(frame) || Math.abs(frame - rounded) > 0.001) {
      throw new Error(`Visual sample ${label} must resolve to an integer frame`);
    }
    return rounded;
  };
  if (!Number.isFinite(fps) || fps <= 0 || !Number.isFinite(mediaStart) || mediaStart < 0
    || !Number.isFinite(duration) || duration <= 0) {
    throw new Error("Visual sample source requires valid fps, media start, and duration");
  }
  const startFrame = exactFrame(mediaStart, "media start");
  const endFrame = startFrame + exactFrame(duration, "duration");
  return buildComposition(directory, { startFrame, endFrame, outputPath });
};

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  const [directory, ...args] = process.argv.slice(2);
  if (!directory) {
    console.error("Usage: node build-composition.mjs <hyperframes-directory> [--start-frame <frame> --end-frame <frame>] [--video-only] [--output <path>]");
    process.exit(64);
  }
  const valueAfter = (flag) => {
    const index = args.indexOf(flag);
    return index === -1 ? undefined : args[index + 1];
  };
  const result = buildComposition(directory, {
    startFrame: valueAfter("--start-frame"),
    endFrame: valueAfter("--end-frame"),
    videoOnly: args.includes("--video-only"),
    outputPath: valueAfter("--output")
  });
  console.log(`Built ${result.outputPath} (${result.endFrame - result.startFrame} frames, ${result.beatIds.length} MG module(s))`);
}
